def build_expansion() -> list[CefrWord]:
    """Combine the bundled lists into a flat list of ``CefrWord`` records.

    A word that appears in more than one band (e.g. ``challenge`` is in both
    A2 and B2/C1 lists) is kept only at its first (lowest) band, so the
    returned list is unique on the case-folded word.
    """

    out: list[CefrWord] = []
    seen: set[str] = set()
    for word, pos, category in _OXFORD_A1:
        key = word.casefold()
        if key in seen:
            continue
        seen.add(key)
        out.append(
            CefrWord(
                word=word,
                cefr_level="A1",
                part_of_speech=pos,
                category=category,
                source="oxford_3000_a1",
            )
        )
    for word, pos, category in _OXFORD_A2:
        key = word.casefold()
        if key in seen:
            continue
        seen.add(key)
        out.append(
            CefrWord(
                word=word,
                cefr_level="A2",
                part_of_speech=pos,
                category=category,
                source="oxford_3000_a2",
            )
        )
    for word, pos, category in _CEFRJ_B2_C1:
        key = word.casefold()
        if key in seen:
            continue
        seen.add(key)
        # Alternate B2/C1 across the curated band so both tiers are
        # represented; the precise split is heuristic but stable.
        level = "B2" if len(out) % 2 == 0 else "C1"
        out.append(
            CefrWord(
                word=word,
                cefr_level=level,
                part_of_speech=pos,
                category=category,
                source="cefrj_b2_c1",
            )
        )
    return out


def dedupe_against_seed(
    expansion: list[CefrWord], seed_words: set[str]
) -> list[CefrWord]:
    """Drop expansion words already present in the app seed bank.

    ``seed_words`` is a set of case-folded word strings read from
    ``app_cefr_words.jsonl`` (the output of ``collect_cefr_words.py``).
    """

    return [w for w in expansion if w.word.casefold() not in seed_words]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Expand the seed CEFR bank with bundled Oxford 3000 / CEFR-J lists."
    )
    parser.add_argument(
        "--seed",
        type=Path,
        default=RAW_DIR / "app_cefr_words.jsonl",
        help="Path to app_cefr_words.jsonl produced by collect_cefr_words.py.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=RAW_DIR / "expanded_wordlist.jsonl",
        help="Output JSONL path.",
    )
    args = parser.parse_args(argv)

    ensure_dirs()

    seed_words: set[str] = set()
    if args.seed.exists():
        for row in read_jsonl(args.seed):
            word = str(row.get("word", "")).strip().casefold()
            if word:
                seed_words.add(word)

    expansion = build_expansion()
    expansion = dedupe_against_seed(expansion, seed_words)

    # Also drop duplicates within the expansion itself (last occurrence wins
    # so the more specific later bands override earlier ones).
    by_word: dict[str, CefrWord] = {}
    for record in expansion:
        by_word[record.word.casefold()] = record
    unique = list(by_word.values())

    count = write_jsonl(args.out, (r.to_jsonl_dict() for r in unique))
    print(f"Expanded wordlist: {count} unique words (seed had {len(seed_words)})")
    print(f"Wrote {args.out}")
    return 0


