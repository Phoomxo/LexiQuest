def render(d):
    if d.key not in (SCAN, READY):
        return False
    entry = d.key == SCAN
    title = d.screens[d.key][1]
    d.back()
    d.text(24, 82, title, 28, d.ink, True)
    d.text(24, 132, "ลองหาคำศัพท์จากสิ่งเดียวในภาพ" if entry else "จัดให้ถ้วยอยู่ตรงกลางกรอบ", 18, d.sub)
    paper, dark, accent = "#EFF1F6", "#28384B", "#FFE09B"
    panel = d.add(d.frame, "frame", "ภาพตัวอย่างถ้วย", 24, 194, 342, 265, dark,
                  children=[], clip=True, corners={"radii": [14]*4, "smoothing": 0})
    d.text(15, 11, "ภาพตัวอย่าง", 15, paper, True, 180, panel)
    for x, y, dx, dy in [(26, 51, 0, 0), (292, 51, 17, 0), (26, 224, 0, -17), (292, 224, 17, -17)]:
        d.box(x, y, 20, 3, paper, parent=panel)
        d.box(x+dx, y+dy, 3, 20, paper, parent=panel)
    d.box(195, 108, 42, 51, accent, 17, panel, "หูถ้วย")
    d.box(202, 118, 26, 31, dark, 9, panel, "ช่องหูถ้วย")
    d.box(105, 97, 110, 82, accent, 19, panel, "ถ้วย")
    d.box(106, 90, 108, 24, "#EDC37D", 0, panel, "ปากถ้วย", "ellipse")
    d.box(114, 97, 92, 10, "#774737", 0, panel, "เครื่องดื่ม", "ellipse")
    d.box(93, 184, 147, 6, paper, 3, panel, "จานรอง")
    d.text(24, 498, "ตรวจคำก่อนเก็บเข้าคลัง" if entry else "พร้อมถ่ายภาพ", 22, d.ink, True)
    d.text(24, 545, "ขั้นตอนนี้ใช้ภาพถ้วยตัวอย่างแทนกล้อง" if entry else "เครื่องจะหาคำอังกฤษและคำแปลที่มีอยู่", 16, d.sub)
    for index, (label, dest) in enumerate(d.screens[d.key][4]):
        n = d.link(24, 598+62*index, 342, 50, label, dest, "#3942AD" if not index else "#EBEDF9", 10)
        d.text(17, 10, label, 18, "#FFFFFF" if not index else d.ink, True, 290, n)
        d.text(310, 6, "›", 24, "#FFFFFF" if not index else d.ink, True, 20, n)
    if entry:
        more = d.link(24, 741, 342, 48, "ลองสถานการณ์อื่น", "_scan_examples")
        d.text(0, 9, "ลองสถานการณ์อื่น", 16, d.sub, True, 320, more)
    return True
